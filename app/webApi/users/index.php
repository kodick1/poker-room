<?php

include_once('../../config/database.php');

$c = new Database();

$d = $c->conectar();

/*
|--------------------------------------------------------------------------
| VALIDAR CONEXIÓN
|--------------------------------------------------------------------------
*/

if (!$d) {

    die('Error de conexión');
}

/*
|--------------------------------------------------------------------------
| QUERY
|--------------------------------------------------------------------------
*/

$sql = "SELECT * FROM usuario";

/*
|--------------------------------------------------------------------------
| PREPARAR
|--------------------------------------------------------------------------
*/

$stmt = $d->prepare($sql);

/*
|--------------------------------------------------------------------------
| EJECUTAR
|--------------------------------------------------------------------------
*/

$stmt->execute();

/*
|--------------------------------------------------------------------------
| OBTENER RESULTADOS
|--------------------------------------------------------------------------
*/

$usuarios = $stmt->fetchAll(PDO::FETCH_ASSOC);

/*
|--------------------------------------------------------------------------
| MOSTRAR JSON
|--------------------------------------------------------------------------
*/

header('Content-Type: application/json');

echo json_encode(
    $usuarios,
    JSON_PRETTY_PRINT
);